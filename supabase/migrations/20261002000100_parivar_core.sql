-- Parivar Path production schema for Supabase.
-- Apply with `supabase db push`; never run this with the service key from a browser.

create extension if not exists pgcrypto;

create table if not exists public.districts (
  state text not null,
  name text not null,
  primary key (state, name)
);

create table if not exists public.trades (
  id bigint generated by default as identity primary key,
  name_en text not null,
  name_local jsonb not null default '{}'::jsonb,
  sector text not null,
  nsqf_level smallint,
  duration_months smallint,
  entry_qualification text,
  safety_notes text,
  job_roles jsonb not null default '[]'::jsonb,
  description_simple jsonb not null default '{}'::jsonb
);

create table if not exists public.providers (
  id bigint generated by default as identity primary key,
  name text not null,
  type text not null,
  state text not null,
  district text not null,
  accreditation text,
  fee_inr integer,
  contact text,
  foreign key (state, district) references public.districts(state, name)
);

create table if not exists public.outcomes (
  id bigint generated by default as identity primary key,
  trade_id bigint not null references public.trades(id),
  state text not null,
  district text,
  cohort_year smallint not null,
  placement_rate numeric(5,2),
  avg_start_salary_inr integer,
  salary_3yr_min integer,
  salary_3yr_max integer,
  self_employment_rate numeric(5,2),
  sample_size integer not null check (sample_size >= 0),
  source text not null,
  verified_on date,
  verified boolean not null default false,
  is_synthetic boolean not null default false,
  evidence_url text,
  review_status text not null default 'pending_data_review' check (review_status in ('pending_data_review', 'reviewed', 'rejected')),
  foreign key (state, district) references public.districts(state, name),
  check (placement_rate is null or placement_rate between 0 and 100),
  check (self_employment_rate is null or self_employment_rate between 0 and 100)
);

create table if not exists public.pathways (
  id bigint generated by default as identity primary key,
  from_trade_id bigint not null references public.trades(id),
  step_order smallint not null,
  step_title text not null,
  nsqf_level smallint,
  next_education text,
  typical_role text,
  typical_salary_range text
);

create table if not exists public.schemes (
  id bigint generated by default as identity primary key,
  name text not null,
  state text,
  eligibility jsonb not null default '{}'::jsonb,
  benefit text,
  how_to_apply text,
  official_url text,
  verified boolean not null default false,
  is_synthetic boolean not null default false,
  verified_on date
);

create table if not exists public.stories (
  id bigint generated by default as identity primary key,
  trade_id bigint references public.trades(id),
  district text,
  name text,
  quote jsonb not null default '{}'::jsonb,
  outcome text,
  is_synthetic boolean not null default true,
  verified boolean not null default false
);

create table if not exists public.staff_roles (
  user_id uuid not null references auth.users(id) on delete cascade,
  role text not null check (role in ('admin', 'counsellor')),
  language text not null default 'te' check (language in ('en', 'te', 'hi')),
  district text,
  created_at timestamptz not null default now(),
  primary key (user_id, role)
);

create table if not exists public.sessions (
  id uuid primary key default gen_random_uuid(),
  owner_id uuid not null references auth.users(id) on delete cascade default auth.uid(),
  lang text not null check (lang in ('en', 'hi', 'te')),
  state text not null,
  district text not null,
  user_role text not null check (user_role in ('learner', 'parent', 'both')),
  learner_class text not null check (char_length(learner_class) between 1 and 30),
  income_bracket text not null check (char_length(income_bracket) between 1 and 30),
  selected_trade_id bigint references public.trades(id),
  consent boolean not null check (consent),
  created_at timestamptz not null default now(),
  foreign key (state, district) references public.districts(state, name)
);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.sessions(id) on delete cascade,
  speaker text not null check (speaker in ('learner', 'parent', 'ai', 'counsellor')),
  text text not null check (char_length(text) between 1 and 1000),
  lang text not null check (lang in ('en', 'hi', 'te')),
  created_at timestamptz not null default now()
);

create table if not exists public.events (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.sessions(id) on delete cascade,
  type text not null,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.message_analysis (
  message_id bigint primary key references public.messages(id) on delete cascade,
  objection_category text,
  sentiment numeric(4,3) check (sentiment between -1 and 1),
  intent text
);

create table if not exists public.escalations (
  id bigint generated by default as identity primary key,
  session_id uuid not null references public.sessions(id) on delete cascade,
  reason text not null check (char_length(reason) between 1 and 1000),
  summary text,
  status text not null default 'new' check (status in ('new', 'assigned', 'contacted', 'resolved', 'closed_no_response')),
  priority text not null default 'normal' check (priority in ('normal', 'high', 'urgent')),
  language text not null default 'te' check (language in ('en', 'te', 'hi')),
  district text,
  sla_due_at timestamptz,
  counsellor_id uuid references auth.users(id),
  callback_slot text,
  created_at timestamptz not null default now(),
  accepted_at timestamptz,
  resolved_at timestamptz,
  resolution_note text,
  family_changed_mind boolean
);

create table if not exists public.escalation_contacts (
  escalation_id bigint primary key references public.escalations(id) on delete cascade,
  callback_phone text not null check (callback_phone ~ '^[6-9][0-9]{9}$'),
  consented boolean not null check (consented),
  expires_at timestamptz not null default (now() + interval '30 days')
);

create table if not exists public.audit_log (
  id bigint generated by default as identity primary key,
  actor_id uuid references auth.users(id),
  entity text not null,
  entity_id text not null,
  action text not null,
  created_at timestamptz not null default now()
);

create index if not exists messages_session_created_idx on public.messages(session_id, created_at);
create index if not exists sessions_district_idx on public.sessions(district);
create index if not exists outcomes_trade_location_year_idx on public.outcomes(trade_id, state, district, cohort_year desc);
create index if not exists escalations_status_created_idx on public.escalations(status, created_at);
create index if not exists events_session_type_idx on public.events(session_id, type, created_at);
create index if not exists staff_roles_role_district_idx on public.staff_roles(role, district);

create or replace function public.purge_expired_escalation_contacts()
returns integer
language plpgsql security definer set search_path = public
as $$
declare deleted_count integer;
begin
  delete from public.escalation_contacts where expires_at <= now();
  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$$;

create or replace function public.is_staff(required_role text default null)
returns boolean
language sql stable security definer set search_path = public, auth
as $$
  select exists (
    select 1 from public.staff_roles r
    where r.user_id = auth.uid()
      and (required_role is null or r.role = required_role)
  )
$$;

create or replace function public.insert_ai_message(
  target_session_id uuid,
  message_text text,
  message_lang text
)
returns public.messages
language plpgsql security definer set search_path = public
as $$
declare inserted public.messages;
begin
  if not exists (select 1 from public.sessions where id = target_session_id and owner_id = auth.uid()) then
    raise exception 'session_not_owned';
  end if;
  insert into public.messages(session_id, speaker, text, lang)
  values (target_session_id, 'ai', message_text, message_lang)
  returning * into inserted;
  return inserted;
end;
$$;

revoke all on function public.insert_ai_message(uuid, text, text) from public, anon;
grant execute on function public.insert_ai_message(uuid, text, text) to authenticated;

