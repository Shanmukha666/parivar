create policy messages_session_read on public.messages for select to authenticated using (
  exists (select 1 from public.sessions s where s.id = session_id and s.owner_id = auth.uid())
  or exists (select 1 from public.escalations e where e.session_id = session_id and e.counsellor_id = auth.uid() and e.status in ('assigned', 'contacted'))
  or public.is_staff('admin')
);
create policy messages_family_insert on public.messages for insert to authenticated with check (
  speaker in ('learner', 'parent') and exists (select 1 from public.sessions s where s.id = session_id and s.owner_id = auth.uid())
);
create policy messages_staff_insert on public.messages for insert to authenticated with check (
  speaker = 'counsellor' and public.is_staff('counsellor') and exists (
    select 1 from public.escalations e where e.session_id = session_id and e.counsellor_id = auth.uid() and e.status in ('assigned', 'contacted')
  )
);

create policy analysis_staff_read on public.message_analysis for select to authenticated using (public.is_staff('admin'));
create policy escalations_owner_read on public.escalations for select to authenticated using (
  session_id in (select id from public.sessions where owner_id = auth.uid())
  or public.is_staff('admin')
  or counsellor_id = auth.uid()
);
create policy escalations_owner_insert on public.escalations for insert to authenticated with check (session_id in (select id from public.sessions where owner_id = auth.uid()));
create policy escalations_staff_update on public.escalations for update to authenticated using (public.is_staff() and (counsellor_id = auth.uid() or public.is_staff('admin')));
create policy events_owner_insert on public.events for insert to authenticated with check (session_id in (select id from public.sessions where owner_id = auth.uid()));
create policy events_owner_read on public.events for select to authenticated using (session_id in (select id from public.sessions where owner_id = auth.uid()) or public.is_staff('admin'));
create policy contacts_owner_insert on public.escalation_contacts for insert to authenticated with check (escalation_id in (select e.id from public.escalations e join public.sessions s on s.id = e.session_id where s.owner_id = auth.uid()));
create policy contacts_assigned_read on public.escalation_contacts for select to authenticated using (escalation_id in (select id from public.escalations where counsellor_id = auth.uid() and status in ('assigned', 'contacted')));
create policy audit_admin_read on public.audit_log for select to authenticated using (public.is_staff('admin'));

