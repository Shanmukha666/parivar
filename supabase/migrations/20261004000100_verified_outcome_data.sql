-- Normalized, provenance-first outcome data contract.
-- Quantitative claims must reference a source and an explicit review state.

create table if not exists public.data_sources (
  id bigint generated by default as identity primary key,
  publisher text not null,
  title text not null,
  source_url text,
  document_reference text,
  retrieved_on date,
  created_at timestamptz not null default now(),
  check (source_url is not null or document_reference is not null)
);

create table if not exists public.outcome_metrics (
  id bigint generated by default as identity primary key,
  trade_id bigint not null references public.trades(id) on delete cascade,
  provider_id bigint references public.providers(id) on delete set null,
  state text not null,
  district text,
  metric_key text not null check (metric_key in (
    'placement_rate',
    'starting_earnings',
    'earnings_after_period',
    'self_employment_rate',
    'job_roles',
    'progression',
    'nsqf_level'
  )),
  metric_value numeric,
  metric_text text,
  unit text not null,
  period_start date,
  period_end date,
  year smallint,
  sample_size integer check (sample_size is null or sample_size >= 0),
  source_id bigint not null references public.data_sources(id),
  verification_date date,
  verification_status text not null default 'pending'
    check (verification_status in ('verified', 'pending', 'rejected')),
  data_quality text not null default 'unknown'
    check (data_quality in ('high', 'medium', 'low', 'unknown')),
  confidence numeric(4,3) check (confidence is null or confidence between 0 and 1),
  is_synthetic boolean not null default false,
  created_at timestamptz not null default now(),
  check (metric_value is not null or metric_text is not null),
  check (verification_status <> 'verified' or (
    is_synthetic = false and verification_date is not null
  )),
  check (metric_key not in ('placement_rate', 'self_employment_rate')
    or metric_value between 0 and 100),
  foreign key (state, district) references public.districts(state, name)
);

alter table public.providers add column if not exists verified boolean not null default false;
alter table public.providers add column if not exists is_synthetic boolean not null default false;
alter table public.providers add column if not exists source_id bigint references public.data_sources(id);

alter table public.pathways add column if not exists source_id bigint references public.data_sources(id);
alter table public.pathways add column if not exists verification_status text not null default 'pending'
  check (verification_status in ('verified', 'pending', 'rejected'));
alter table public.pathways add column if not exists is_synthetic boolean not null default false;

alter table public.data_sources enable row level security;
alter table public.outcome_metrics enable row level security;

drop policy if exists data_sources_public_read on public.data_sources;
create policy data_sources_public_read on public.data_sources
  for select to anon, authenticated using (true);

drop policy if exists outcome_metrics_public_read on public.outcome_metrics;
create policy outcome_metrics_public_read on public.outcome_metrics
  for select to anon, authenticated using (true);

create index if not exists outcome_metrics_trade_location_idx
  on public.outcome_metrics(trade_id, state, district, year desc);
create index if not exists outcome_metrics_provider_idx
  on public.outcome_metrics(provider_id, metric_key, year desc);
create index if not exists outcome_metrics_verification_idx
  on public.outcome_metrics(verification_status, is_synthetic, verification_date desc);
create index if not exists outcome_metrics_source_idx
  on public.outcome_metrics(source_id);
create index if not exists providers_location_verified_idx
  on public.providers(state, district, verified, is_synthetic);
create index if not exists pathways_trade_verification_idx
  on public.pathways(from_trade_id, verification_status, is_synthetic, step_order);

create or replace view public.current_outcome_metrics as
select
  m.*,
  s.publisher,
  s.title as source_title,
  s.source_url,
  s.document_reference
from public.outcome_metrics m
join public.data_sources s on s.id = m.source_id
where m.verification_status = 'verified'
  and m.is_synthetic = false;

