create or replace function public.purge_expired_family_data()
returns integer
language plpgsql security definer set search_path = public
as $$
declare deleted_count integer;
begin
  delete from public.sessions
  where created_at < now() - interval '730 days'
    and not exists (
      select 1 from public.escalations e
      where e.session_id = sessions.id
        and e.status in ('new', 'assigned', 'contacted')
    );
  get diagnostics deleted_count = row_count;
  perform public.purge_expired_escalation_contacts();
  return deleted_count;
end;
$$;

do $$
begin
  if exists (select 1 from pg_available_extensions where name = 'pg_cron') then
    create extension if not exists pg_cron;
    perform cron.schedule(
      'parivar-purge-expired-family-data',
      '17 2 * * *',
      $job$select public.purge_expired_family_data()$job$
    )
    where not exists (
      select 1 from cron.job where jobname = 'parivar-purge-expired-family-data'
    );
  end if;
end;
$$;
